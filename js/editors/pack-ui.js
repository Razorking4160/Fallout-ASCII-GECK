/* Studio side of content packs. Export gathers the browser's saved maps, Forge
   definitions and authored jobs into one JSON file; import merges a pack into
   those same stores and reloads so every view sees the new content. */
(function (WA) {
  'use strict';
  const U = WA.util;
  const $ = U.el;

  const msg = t => { const el = $('pmsg'); if (el) el.textContent = t; };

  function download(name, text, mime) {
    try {
      const a = document.createElement('a');
      a.href = URL.createObjectURL(new Blob([text], { type: mime || 'application/json' }));
      a.download = name;
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(a.href), 2000);
      return true;
    } catch (e) { return false; }
  }

  const packName = () => {
    const s = $('pname') && $('pname').value.trim();
    return (s || 'Wasteland content ' + new Date().toISOString().slice(0, 10)).slice(0, 60);
  };

  function defCount(defs) {
    return ['tiles', 'entities', 'items']
      .reduce((n, k) => n + Object.keys(defs[k] || {}).length, 0);
  }

  async function exportPack() {
    if (!WA.mapStore) return msg('Map storage is not loaded.');
    let maps = {};
    try { maps = await WA.mapStore.all(); }
    catch (e) { return msg('Could not read the map library.'); }
    const store = WA.authoring ? WA.authoring.exportStore() : { quests: {}, dialogue: {} };
    const pack = {
      format: 'wasteland-content', version: 1,
      name: packName(), created: new Date().toISOString(),
      defs: WA.forge.exportDefs(), maps,
      quests: store.quests, dialogue: store.dialogue
    };
    const v = WA.pack.validate(pack);
    if (!v.ok) return msg('Not exported: ' + v.errors.slice(0, 3).join(' '));
    const ok = download('wasteland-content.json', JSON.stringify(pack, null, 2));
    msg(ok
      ? `Exported ${Object.keys(maps).length} map(s), ${Object.keys(store.quests).length} job(s) and ${defCount(pack.defs)} definition(s).`
      : 'Could not write the file. Try again from a browser that allows downloads.');
  }

  function exportDefs() {
    const defs = WA.forge.exportDefs();
    const txt = '/* Authored definitions. Generated by G.E.C.K. → Forge → Export definitions\n' +
      '   for game; the studio rewrites this whole file, so do not hand-edit it. */\n' +
      '(function (WA) {\n  WA.AUTHORED_DEFS = ' + JSON.stringify(defs, null, 2) + ';\n})(window.WA = window.WA || {});\n';
    const ok = download('defs-authored.js', txt, 'text/javascript');
    msg(ok
      ? `Exported ${defCount(defs)} definition(s). Replace game/js/data/defs-authored.js with the downloaded file.`
      : 'Could not write the file. Use Export content pack instead.');
  }

  async function importPack(file) {
    if (!file) return;
    msg('Reading pack…');
    let raw;
    try { raw = JSON.parse(await file.text()); }
    catch (e) { return msg('That file is not valid JSON.'); }
    const v = WA.pack.validate(raw);
    if (!v.ok) return msg('Import failed: ' + v.errors.slice(0, 3).join(' '));
    const pack = v.pack;
    const nd = WA.forge.importDefs(pack.defs);
    let nm = 0;
    for (const id of Object.keys(pack.maps)) {
      if (WA.mapStore && await WA.mapStore.put(id, pack.maps[id])) nm++;
    }
    const nq = WA.authoring ? WA.authoring.importStore(pack.quests, pack.dialogue) : 0;
    msg(`Imported ${nm} map(s), ${nq} job/dialogue entr${nq === 1 ? 'y' : 'ies'} and ${nd} definition(s). Reloading…`);
    setTimeout(() => location.reload(), 700);
  }

  function init() {
    if (!$('pexport')) return;
    $('pexport').onclick = exportPack;
    $('pdefs').onclick = exportDefs;
    $('pfile').onchange = e => {
      const f = e.target.files && e.target.files[0];
      importPack(f).catch(err => msg('Import failed: ' + err.message));
      e.target.value = '';
    };
    if ($('pname') && !$('pname').value) $('pname').value = packName();
  }

  WA.packUI = { init, exportPack, exportDefs, importPack };
})(window.WA = window.WA || {});
